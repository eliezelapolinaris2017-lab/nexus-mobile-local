const normalize=s=>String(s||'').normalize('NFD').replace(/[\u0300-\u036f]/g,'').toLowerCase();
const compact=s=>normalize(s).replace(/[^a-z0-9]/g,'');
export function searchHvac(query='',brand='',category=''){
 const q=normalize(query).trim(),compactQuery=compact(q);
 return HVAC_CODES.filter(r=>(!brand||r.brand===brand)&&(!category||r.category===category)&&(!q||q.split(/\s+/).every(t=>normalize([r.code,r.brand,r.series,r.category,r.meaning,CHECKS[r.category]].join(' ')).includes(t))||compact(r.code)===compactQuery||compact(r.code).startsWith(compactQuery))).sort((a,b)=>(compact(b.code)===compactQuery)-(compact(a.code)===compactQuery));
}
